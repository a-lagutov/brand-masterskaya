import { createHmac, timingSafeEqual } from 'node:crypto';

export type CabinetToken = {
  purpose: 'session' | 'playback' | 'oauth';
  issuedAt: number;
  expiresAt: number;
  memberId?: number;
  sessionId?: string;
  lectureId?: number;
  revision?: string;
  state?: string;
  verifier?: string;
};

/** Signs short-lived, purpose-bound tokens; no encryption keys are embedded in them. */
export function signToken(
  data: Omit<CabinetToken, 'issuedAt' | 'expiresAt'>,
  secret: string,
  lifetime: number,
  now = Math.floor(Date.now() / 1000),
): string {
  if (secret.length < 32) throw new Error('Cabinet secret must contain at least 32 characters');
  const body = Buffer.from(
    JSON.stringify({ ...data, issuedAt: now, expiresAt: now + lifetime }),
  ).toString('base64url');
  return `${body}.${createHmac('sha256', secret).update(`cabinet:${body}`).digest('base64url')}`;
}

/** Rejects malformed, expired, future-issued or differently scoped tokens without throwing. */
export function verifyToken(
  value: string,
  secret: string,
  purpose: CabinetToken['purpose'],
  now = Math.floor(Date.now() / 1000),
): CabinetToken | null {
  if (secret.length < 32 || value.length > 4096) return null;
  const [body, signature, extra] = value.split('.');
  if (!body || !signature || !/^[A-Za-z0-9_-]{43}$/.test(signature) || extra !== undefined)
    return null;
  const expected = createHmac('sha256', secret).update(`cabinet:${body}`).digest('base64url');
  if (
    signature.length !== expected.length ||
    !timingSafeEqual(Buffer.from(signature), Buffer.from(expected))
  )
    return null;
  try {
    const token = JSON.parse(Buffer.from(body, 'base64url').toString('utf8')) as CabinetToken;
    return token.purpose === purpose &&
      Number.isSafeInteger(token.issuedAt) &&
      Number.isSafeInteger(token.expiresAt) &&
      token.issuedAt <= now &&
      token.expiresAt > now
      ? token
      : null;
  } catch {
    return null;
  }
}

/** Prevents reuse of a playback URL in another login session, lecture or upload revision. */
export function playbackMatches(
  token: CabinetToken,
  session: Pick<CabinetToken, 'memberId' | 'sessionId'>,
  lectureId: number,
  revision: string,
): boolean {
  return Boolean(
    session.memberId &&
    session.sessionId &&
    token.memberId === session.memberId &&
    token.sessionId === session.sessionId &&
    token.lectureId === lectureId &&
    token.revision === revision,
  );
}

/** Allows only files generated by our packager, never raw source uploads or arbitrary paths. */
export function safeMediaName(filename: string): boolean {
  return /^(?:manifest\.mpd|master\.m3u8|(?:video|audio)\.m3u8|(?:video|audio)-init\.mp4|(?:video|audio)-\d+\.m4s)$/.test(
    filename,
  );
}

/** Derives distinct AES content keys and public key identifiers for immutable upload revisions. */
export function contentKeys(revision: string, secret: string): { key: string; keyId: string } {
  if (secret.length < 32) throw new Error('Cabinet secret must contain at least 32 characters');
  return {
    key: createHmac('sha256', secret)
      .update(`cabinet-content:${revision}`)
      .digest('hex')
      .slice(0, 32),
    keyId: createHmac('sha256', secret)
      .update(`cabinet-key-id:${revision}`)
      .digest('hex')
      .slice(0, 32),
  };
}
